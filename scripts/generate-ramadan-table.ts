import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const FIRST_YEAR = 1900;
const LAST_YEAR = 2100;
const DAY_MS = 86_400_000;
const OUT = join(import.meta.dir, "..", "crates", "engine", "src", "ramadan_table.rs");

const hijri = new Intl.DateTimeFormat("en-u-ca-islamic-umalqura", {
  year: "numeric",
  month: "numeric",
  day: "numeric",
  timeZone: "UTC",
});

function hijriParts(dayIndex: number): { year: number; month: number } {
  const parts = hijri.formatToParts(dayIndex * DAY_MS);
  const get = (type: string) => Number(parts.find((p) => p.type === type)?.value);
  return { year: get("year") || get("relatedYear"), month: get("month") };
}

const start = Date.UTC(FIRST_YEAR, 0, 1) / DAY_MS;
const end = Date.UTC(LAST_YEAR, 11, 31) / DAY_MS;
const rows: string[] = [];
let open: { year: number; first: number } | undefined;

for (let day = start; day <= end + 1; day++) {
  const { year, month } = hijriParts(day);
  if (month === 9 && !open) open = { year, first: day };
  if (month !== 9 && open) {
    rows.push(`    Ramadan { hijri_year: ${open.year}, first_day: ${open.first}, end_day: ${day} },`);
    open = undefined;
  }
}

const source = `// @generated by scripts/generate-ramadan-table.ts. Do not edit by hand.

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(crate) struct Ramadan {
    pub(crate) hijri_year: u16,
    pub(crate) first_day: i32,
    pub(crate) end_day: i32,
}

#[rustfmt::skip]
pub(crate) const RAMADANS: &[Ramadan] = &[
${rows.join("\n")}
];
`;

const withoutIcuVersion = (text: string): string => text.replace(/\(ICU [^)]*\)/, "(ICU)");

if (process.argv.includes("--check")) {
  if (withoutIcuVersion(readFileSync(OUT, "utf8")) !== withoutIcuVersion(source)) {
    console.error("ramadan_table.rs is stale; run bun scripts/generate-ramadan-table.ts");
    process.exit(1);
  }
} else {
  writeFileSync(OUT, source);
  console.log(`wrote ${rows.length} Ramadan entries to ${OUT}`);
}
